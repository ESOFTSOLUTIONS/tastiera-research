#!/usr/bin/env python3
"""Build the Tastiera lexicon from open sources.

Sources (downloaded into dictionary/sources/, not committed):
  - bgodole/korrektor  Hunspell sq_AL (GPL-3.0), ~1.3M word forms based on
    "Fjalori i madh i gjuhës shqipe" (2026) — decides which words are VALID.
  - hermitdave/FrequencyWords sq_50k (code MIT, data CC-BY-SA-4.0, OpenSubtitles 2018)
    — word FREQUENCIES (contains misspellings, so it is filtered by Hunspell).

Outputs (committed, consumed by services/ai and the keyboards):
  data/lexicon.tsv      word<TAB>freq       valid words, most frequent first
  data/autocorrect.tsv  typed<TAB>correct   safe context-free corrections (diacritics)
  data/hunspell/        cleaned sq_AL.dic/.aff for full validity checks on the server

Usage:  python build_lexicon.py   (needs: pip install spylls certifi)
"""

from __future__ import annotations

import ssl
import urllib.request
from collections import defaultdict
from pathlib import Path

from spylls.hunspell import Dictionary

ROOT = Path(__file__).resolve().parent
SRC = ROOT / "sources"
OUT = ROOT / "data"

SOURCES = {
    "sq_AL.dic": "https://raw.githubusercontent.com/bgodole/korrektor/HEAD/sq_AL.dic",
    "sq_AL.aff": "https://raw.githubusercontent.com/bgodole/korrektor/HEAD/sq_AL.aff",
    "korrektor_LICENSE": "https://raw.githubusercontent.com/bgodole/korrektor/HEAD/LICENSE",
    "sq_50k.txt": "https://raw.githubusercontent.com/hermitdave/FrequencyWords/master/content/2018/sq/sq_50k.txt",
}

MIN_FREQ = 3
# A valid typed word is auto-corrected to its diacritic form only if that form is this
# many times more frequent (eshte→është 10x, nje→një 10x; ne→në is only 4x).
RATIO_VALID = 5.0
# Real, common words whose diacritic twin is also common: never auto-correct without
# sentence context (the server's language model decides those).
PROTECTED = {"ne", "te", "se", "me", "ca", "ve", "be", "c", "e", "a", "i", "u", "o"}


def fold(s: str) -> str:
    return s.replace("ë", "e").replace("ç", "c").replace("Ë", "E").replace("Ç", "C")


def diacritics(s: str) -> int:
    return sum(ch in "ëçËÇ" for ch in s)


def fetch() -> None:
    SRC.mkdir(exist_ok=True)
    for name, url in SOURCES.items():
        dest = SRC / name
        if not dest.exists():
            print("download", url)
            try:
                import certifi

                ctx = ssl.create_default_context(cafile=certifi.where())
            except ImportError:
                ctx = ssl.create_default_context()
            with urllib.request.urlopen(url, context=ctx) as r:
                dest.write_bytes(r.read())
    # Normalize CRLF so every Hunspell implementation reads the files.
    for name in ("sq_AL.dic", "sq_AL.aff"):
        text = (SRC / name).read_text(encoding="utf-8").replace("\r\n", "\n")
        (OUT / "hunspell" / name).write_text(text, encoding="utf-8")
    (OUT / "hunspell" / "LICENSE").write_text(
        (SRC / "korrektor_LICENSE").read_text(encoding="utf-8"), encoding="utf-8"
    )


def main() -> None:
    OUT.mkdir(exist_ok=True)
    (OUT / "hunspell").mkdir(exist_ok=True)
    fetch()
    hs = Dictionary.from_files(str(OUT / "hunspell" / "sq_AL"))

    freq: dict[str, int] = {}
    for line in (SRC / "sq_50k.txt").read_text(encoding="utf-8").splitlines():
        word, count = line.rsplit(" ", 1)
        if word.isalpha() and int(count) >= MIN_FREQ:
            freq[word] = int(count)
    valid = {w: hs.lookup(w) for w in freq}

    lexicon = sorted(((w, f) for w, f in freq.items() if valid[w]), key=lambda x: -x[1])
    with open(OUT / "lexicon.tsv", "w", encoding="utf-8") as fh:
        fh.write("# word\tfreq — generated by dictionary/build_lexicon.py\n")
        for w, f in lexicon:
            fh.write(f"{w}\t{f}\n")

    groups: dict[str, list[tuple[str, int]]] = defaultdict(list)
    for w, f in freq.items():
        groups[fold(w)].append((w, f))

    corrections: list[tuple[str, str, int]] = []
    for members in groups.values():
        best_w, best_f = max(((w, f) for w, f in members if valid[w]), key=lambda x: x[1], default=(None, 0))
        if best_w is None:
            continue
        for w, f in members:
            if w == best_w or w in PROTECTED:
                continue
            if diacritics(best_w) <= diacritics(w):
                continue  # only ADD diacritics automatically, never remove user's ë/ç
            if not valid[w] or best_f / f >= RATIO_VALID:
                corrections.append((w, best_w, f))
    corrections.sort(key=lambda x: -x[2])
    with open(OUT / "autocorrect.tsv", "w", encoding="utf-8") as fh:
        fh.write("# typed\tcorrection — generated by dictionary/build_lexicon.py\n")
        for w, c, _ in corrections:
            fh.write(f"{w}\t{c}\n")

    print(f"lexicon: {len(lexicon)} valid words (of {len(freq)}); autocorrect: {len(corrections)} pairs")


if __name__ == "__main__":
    main()
